const fs = require('fs');
const path = require('path');
require('dotenv').config({ path: path.join(__dirname, '../../.env') });
const mysql = require('mysql2/promise');

const dbName = process.env.DB_NAME || 'marketplace';
const outputFile = path.join(__dirname, 'full-dump.sql');
const schemaFile = path.join(__dirname, 'schema.sql');

const tableOrder = [
  'users',
  'packages',
  'products',
  'seller_customers',
  'transactions',
  'pro_usages',
  'stores',
  'tickets',
  'ticket_messages',
  'notifications',
  'reviews',
];

function escapeValue(value) {
  if (value === null || value === undefined) return 'NULL';
  if (value instanceof Date) {
    return `'${value.toISOString().slice(0, 19).replace('T', ' ')}'`;
  }
  if (Buffer.isBuffer(value)) {
    return `X'${value.toString('hex')}'`;
  }
  if (typeof value === 'number' || typeof value === 'bigint') {
    return String(value);
  }
  if (typeof value === 'boolean') {
    return value ? '1' : '0';
  }
  if (typeof value === 'object') {
    return escapeValue(JSON.stringify(value));
  }

  return `'${String(value)
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/\r/g, '\\r')
    .replace(/\n/g, '\\n')}'`;
}

async function exportTable(connection, table) {
  const [rows] = await connection.query(`SELECT * FROM \`${dbName}\`.\`${table}\``);
  if (!rows.length) return `-- Table ${table} has no rows\n\n`;

  const columns = Object.keys(rows[0]).map((column) => `\`${column}\``).join(', ');
  const values = rows
    .map((row) => `(${Object.values(row).map(escapeValue).join(', ')})`)
    .join(',\n');

  return `INSERT INTO \`${table}\` (${columns}) VALUES\n${values};\n\n`;
}

async function main() {
  const connection = await mysql.createConnection({
    host: process.env.DB_HOST || 'localhost',
    port: Number(process.env.DB_PORT || 3306),
    user: process.env.DB_SETUP_USER || process.env.DB_USER || 'root',
    password: process.env.DB_SETUP_PASSWORD ?? process.env.DB_PASSWORD ?? '',
    database: dbName,
  });

  try {
    const schema = fs.readFileSync(schemaFile, 'utf8');
    let dump = '-- Full database dump for Hendabadi Marketplace Panel\n';
    dump += '-- Generated by backend/src/database/export.js\n\n';
    dump += `DROP DATABASE IF EXISTS \`${dbName}\`;\n`;
    dump += `${schema.trim()}\n\n`;
    dump += 'SET FOREIGN_KEY_CHECKS=0;\n\n';

    for (const table of tableOrder) {
      dump += await exportTable(connection, table);
    }

    dump += 'SET FOREIGN_KEY_CHECKS=1;\n';
    fs.writeFileSync(outputFile, dump, 'utf8');
    console.log(`Database dump written to ${outputFile}`);
  } finally {
    await connection.end();
  }
}

main().catch((error) => {
  console.error(error.message);
  process.exit(1);
});
